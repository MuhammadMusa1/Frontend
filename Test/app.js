// Создаем новый экземпляр Vue
new Vue({
    // Привязываемся к элементу с id="app"
    el: '#app',
    
    // Данные приложения (реактивные переменные)
    data: {
        message: 'Привет, Vue!'
    },
    
    // Методы приложения
    methods: {
        // Функция, которая вызывается при клике на кнопку
        changeMessage: function() {
            this.message = 'Vue.js - это круто!';
        }
    }
});